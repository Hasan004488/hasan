// libraries/darkweb-reporter.js

const fs = require('fs');
const PDFDocument = require('pdfkit-table');

// --- Style Constants for the PDF ---
const S = {
    font: { bold: 'Helvetica-Bold', normal: 'Helvetica' },
    font_size: { h1: 22, h2: 18, h3: 14, normal: 11, small: 9 },
    color: { primary: '#0d6efd', secondary: '#6c757d', dark: '#212529' },
    margin: { top: 50, bottom: 50, x: 50 },
};

/**
 * Resets font and color to default styles.
 * @param {PDFDocument} doc The PDF document instance.
 */
function resetStyles(doc) {
    doc.font(S.font.normal).fontSize(S.font_size.normal).fillColor(S.color.dark);
}

/**
 * Renders a footer with page number and generation info on every page.
 * @param {PDFDocument} doc The PDF document instance.
 * @param {string} reporter_name The name of the user who generated the report.
 */
function renderFooter(doc, reporter_name) {
    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
        doc.switchToPage(i);
        const bottom = doc.page.margins.bottom;
        
        // Report generation text
        doc.fontSize(S.font_size.small)
           .fillColor(S.color.secondary)
           .text(`Report generated by: ${reporter_name} on ${new Date().toLocaleString()}`,
                 doc.page.margins.left,
                 doc.page.height - bottom / 1.5,
                 { align: 'center' });
        
        // Page number
        doc.fontSize(S.font_size.small)
           .text(`Page ${i + 1} of ${range.count}`,
                 doc.page.margins.left,
                 doc.page.height - bottom / 1.5,
                 { align: 'right' });
    }
}

/**
 * Generates a PDF report for Dark Web scan results.
 * @param {object} domainData The organization and scan data from the database.
 * @param {string} reporter_name The name of the user generating the report.
 * @param {function(string|null, Error|null)} callback The callback function, returning the file path on success or an error on failure.
 */
async function generateDarkWebPdf(domainData, reporter_name, callback) {
    try {
        const directory = "./reports";
        const filename = `${directory}/dark-web-report-${domainData.organizationName.replace(/\s+/g, '_')}-${Date.now()}.pdf`;

        if (!fs.existsSync(directory)) {
            fs.mkdirSync(directory, { recursive: true });
        }

        const doc = new PDFDocument({
            size: 'A4',
            bufferPages: true,
            margins: { top: S.margin.top, bottom: S.margin.bottom, left: S.margin.x, right: S.margin.x }
        });

        const outputStream = fs.createWriteStream(filename);
        doc.pipe(outputStream);

        // --- Report Header ---
        doc.font(S.font.bold).fontSize(S.font_size.h1).fillColor(S.color.dark);
        doc.text('Dark Web Scan Report', { align: 'center' });
        doc.moveDown(2);
        resetStyles(doc);

        // --- Organization Summary Table ---
        const summaryTable = {
            title: 'Monitored Asset Summary',
            headers: ['Property', 'Value'],
            rows: [
                ['Organization Name', domainData.organizationName || 'N/A'],
                ['Asset Type', domainData.searchType ? domainData.searchType.charAt(0).toUpperCase() + domainData.searchType.slice(1) : 'N/A'],
                ['Asset Value', domainData.name || domainData.ip || domainData.username || domainData.phone || 'N/A'],
                ['Overall Status', domainData.status || 'N/A'],
                ['Last Scanned', domainData.lastScanned ? new Date(domainData.lastScanned).toLocaleString() : 'N/A']
            ]
        };
        await doc.table(summaryTable, { prepareHeader: () => doc.font(S.font.bold) });
        doc.moveDown(2);

        // --- Breach Details Table ---
        const breaches = domainData.scanResult?.data || [];
        if (breaches.length > 0) {
            const breachTable = {
                title: `Found ${breaches.length} Breach Record(s)`,
                headers: ['Timestamp', 'Email', 'Password', 'Phone', 'Username', 'Status'],
                rows: breaches.map(breach => [
                    breach.timestamp ? new Date(breach.timestamp).toLocaleString() : 'N/A',
                    breach.email || 'N/A',
                    breach.password ? '********' : 'N/A',
                    breach.phone || 'N/A',
                    breach.username || 'N/A',
                    breach.manualStatus ? breach.manualStatus.replace('-', ' ') : 'unresolved'
                ])
            };
            await doc.table(breachTable, {
                prepareHeader: () => doc.font(S.font.bold).fontSize(S.font_size.small),
                prepareRow: () => doc.font(S.font.normal).fontSize(S.font_size.small)
            });
        } else {
            doc.font(S.font.bold).fontSize(S.font_size.h3).text('No Breach Records Found', { align: 'center' });
            doc.moveDown();
            resetStyles(doc)
               .text('The scan did not find any compromised credentials or threats related to the monitored asset.', { align: 'center' });
        }

        // --- Finalize Document ---
        renderFooter(doc, reporter_name);
        doc.end();
        outputStream.on('finish', () => callback(filename, null));
        outputStream.on('error', (err) => callback(null, err));

    } catch (err) {
        console.error("Error generating Dark Web PDF report:", err);
        callback(null, err);
    }
}

module.exports = { generateDarkWebPdf };